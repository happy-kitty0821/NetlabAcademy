"""
simulator_core.simulation
~~~~~~~~~~~~~~~~~~~~~~~~~
Simulation runtime: logical clock, event dispatcher, trace recorder, reset.

The Simulation object is the central coordinator.  It owns:
- The logical clock.
- The EventScheduler (priority queue).
- The event trace (inspectable list of all processed events).
- The device protocol objects (Host, Switch) built from the topology.

Device protocol objects call ``simulation.schedule()`` to inject new events.
The dispatcher routes processed events to the correct device handler.

No host I/O, no socket imports.
"""

from __future__ import annotations

import copy
import random
from typing import TYPE_CHECKING, Optional

from simulator_core.events import (
    FrameArrival,
    FrameDropped,
    FrameTransmit,
    SimulationEvent,
    TraceLimitReached,
    BPDUHelloEvent,
    ForwardDelayEvent,
    CDPHelloEvent,
    DROP_LINK_DOWN,
    DROP_INTERFACE_ADMIN_DOWN,
)
from simulator_core.exceptions import SimulationLimitError
from simulator_core.scheduler import EventScheduler
from simulator_core.topology import Topology
from simulator_core.types import InterfaceState, PROPAGATION_DELAY
from dataclasses import dataclass as _dataclass

# Maximum syslog entries kept per simulation (oldest are dropped).
MAX_SYSLOG = 5000


@_dataclass(frozen=True)
class SyslogEntry:
    """One IOS-style syslog message generated by a simulated device."""

    seq: int            # monotonically increasing across the simulation
    tick: int           # logical clock when it was generated
    device_id: str
    hostname: str
    facility: str       # e.g. "LINK", "LINEPROTO", "SYS"
    severity: int       # 0-7, IOS severity levels
    mnemonic: str       # e.g. "UPDOWN", "CHANGED", "CONFIG_I"
    message: str

    @property
    def text(self) -> str:
        """``%LINK-3-UPDOWN: Interface FastEthernet0/1, changed state to up``"""
        return f"%{self.facility}-{self.severity}-{self.mnemonic}: {self.message}"

    def to_dict(self) -> dict:
        return {
            "seq": self.seq, "tick": self.tick, "device_id": self.device_id,
            "hostname": self.hostname, "facility": self.facility,
            "severity": self.severity, "mnemonic": self.mnemonic,
            "message": self.message, "text": self.text,
        }

if TYPE_CHECKING:
    from simulator_core.devices.host import Host
    from simulator_core.devices.switch import Switch
    from simulator_core.devices.router import Router


class Simulation:
    """
    Discrete-event simulation runtime.

    Parameters
    ----------
    topology:
        A validated (or will-be-validated) topology description.
    seed:
        Integer seed for the simulation's PRNG.  Same seed → same trace.
    max_ticks:
        Maximum logical timestamp for any event.  Events beyond this raise
        :class:`~simulator_core.exceptions.SimulationLimitError`.
    max_trace:
        Maximum number of events recorded in the trace.  When reached a
        :class:`~simulator_core.events.TraceLimitReached` sentinel is appended
        and further events are not recorded (the simulation continues).
    max_queue:
        Maximum depth of the event scheduler queue.
    max_nodes, max_links:
        Passed through to topology.validate() for resource-limit checking.
    """

    DEFAULT_MAX_TICKS: int = 3_600
    DEFAULT_MAX_TRACE: int = 50_000
    DEFAULT_MAX_QUEUE: int = 10_000

    def __init__(
        self,
        topology: Topology,
        seed: int = 0,
        max_ticks: int = DEFAULT_MAX_TICKS,
        max_trace: int = DEFAULT_MAX_TRACE,
        max_queue: int = DEFAULT_MAX_QUEUE,
    ) -> None:
        topology.validate()

        # Store a deep copy for reset() so we can always restore initial state.
        self._topology_snapshot: Topology = copy.deepcopy(topology)
        self._topology: Topology = copy.deepcopy(topology)

        self._seed: int = seed
        self._max_ticks: int = max_ticks
        self._max_trace: int = max_trace

        self._rng: random.Random = random.Random(seed)
        self._clock: int = 0
        self._scheduler: EventScheduler = EventScheduler(max_depth=max_queue)
        self._trace: list[SimulationEvent] = []

        # Device protocol objects keyed by device_id.
        self._hosts: dict[str, "Host"] = {}
        self._switches: dict[str, "Switch"] = {}
        self._routers: dict[str, "Router"] = {}
        # Generation counter per switch for BPDUHelloEvent cancellation.
        # Incrementing a switch's generation invalidates all previously
        # scheduled BPDUHelloEvents for that switch (stale-event guard).
        self._hello_generation: dict[str, int] = {}
        # Generation counter per device for CDPHelloEvent cancellation.
        # Mirrors the BPDU generation guard pattern.
        self._cdp_generation: dict[str, int] = {}
        # Guard flag: _trigger_stp is a no-op until _init_devices finishes
        # building all Switch objects and running the initial STP election.
        self._stp_initialized: bool = False
        # Syslog: messages devices emit (link up/down, config changes).
        self._syslog: list[SyslogEntry] = []
        self._syslog_seq: int = 0
        # Last known (admin, oper) state per (device_id, interface) for
        # detecting transitions; empty until the first computation.
        self._iface_states: dict[tuple[str, str], tuple] = {}
        self._init_devices()

    # ------------------------------------------------------------------
    # Public read properties
    # ------------------------------------------------------------------

    @property
    def clock(self) -> int:
        """Current logical tick."""
        return self._clock

    @property
    def trace(self) -> list[SimulationEvent]:
        """A defensive copy of the event trace."""
        return list(self._trace)

    @property
    def topology(self) -> Topology:
        """The working topology (not the reset snapshot)."""
        return self._topology

    # ------------------------------------------------------------------
    # Scheduling
    # ------------------------------------------------------------------

    def schedule(self, event: SimulationEvent) -> None:
        """
        Schedule an event.

        Raises
        ------
        SimulationLimitError
            If ``event.time > max_ticks`` or the queue depth limit is hit.
        """
        if event.time > self._max_ticks:
            raise SimulationLimitError(
                f"Event at tick {event.time} exceeds max_ticks "
                f"{self._max_ticks}."
            )
        self._scheduler.schedule(event)

    def next_seq(self) -> int:
        """Delegate to the scheduler's sequence counter."""
        return self._scheduler.next_seq()

    # ------------------------------------------------------------------
    # Lifecycle
    # ------------------------------------------------------------------

    def step(self) -> Optional[SimulationEvent]:
        """
        Process one event from the queue.

        Returns the processed event, or ``None`` if the queue is empty.
        """
        if self._scheduler.is_empty():
            return None
        event = self._scheduler.pop()
        self._clock = event.time
        self._record(event)
        self._dispatch(event)
        return event

    def run(self) -> None:
        """Process all queued events until the queue is empty."""
        while not self._scheduler.is_empty():
            self.step()

    def reset(self) -> None:
        """
        Restore the simulation to its initial state.

        After reset, replaying the same sequence of host.ping() calls with
        the same arguments will produce the identical event trace.
        """
        self._clock = 0
        self._rng = random.Random(self._seed)
        self._scheduler.clear()
        self._trace.clear()
        self._topology = copy.deepcopy(self._topology_snapshot)
        self._hosts.clear()
        self._switches.clear()
        self._routers.clear()
        # Increment all existing generations so queued BPDUHelloEvents become stale.
        for dev_id in list(self._hello_generation):
            self._hello_generation[dev_id] += 1
        # Increment CDP generations so queued CDPHelloEvents become stale.
        for dev_id in list(self._cdp_generation):
            self._cdp_generation[dev_id] += 1
        self._stp_initialized = False
        self._syslog.clear()
        self._iface_states.clear()
        self._init_devices()

    # ------------------------------------------------------------------
    # Syslog
    # ------------------------------------------------------------------

    @property
    def syslog(self) -> list[SyslogEntry]:
        """All retained syslog entries, oldest first."""
        return list(self._syslog)

    @property
    def syslog_last_seq(self) -> int:
        return self._syslog_seq

    def syslog_since(self, seq: int, device_id: Optional[str] = None) -> list[SyslogEntry]:
        """Entries with a sequence number greater than *seq*."""
        return [
            e for e in self._syslog
            if e.seq > seq and (device_id is None or e.device_id == device_id)
        ]

    def log_event(self, device_id: str, facility: str, severity: int,
                  mnemonic: str, message: str) -> None:
        """Record a syslog message for a device (also kept in its log buffer)."""
        from simulator_core.device_config import LogSeverity
        device = self._topology.devices.get(device_id)
        if device is None:
            return
        self._syslog_seq += 1
        self._syslog.append(SyslogEntry(
            seq=self._syslog_seq, tick=self._clock, device_id=device_id,
            hostname=device.hostname, facility=facility, severity=severity,
            mnemonic=mnemonic, message=message,
        ))
        if len(self._syslog) > MAX_SYSLOG:
            del self._syslog[: len(self._syslog) - MAX_SYSLOG]
        try:
            device.config.add_log(
                self._clock, LogSeverity(severity), facility, message, mnemonic=mnemonic,
            )
        except (ValueError, AttributeError):
            pass

    def _log_interface_transitions(self) -> None:
        """
        Compare interface states with the last known ones and emit the IOS
        messages for each change (switches and routers only):

        - shutdown:            %LINK-5-CHANGED ... administratively down
        - link comes up:       %LINK-3-UPDOWN ... up, %LINEPROTO-5-UPDOWN ... up
        - link goes down:      %LINK-3-UPDOWN ... down, %LINEPROTO-5-UPDOWN ... down
        - no shutdown, no cable: %LINK-3-UPDOWN ... down

        On the first computation every interface is treated as previously
        down, so a lab start logs the ports that come up (as a booting
        device does).
        """
        from simulator_core.naming import long_name
        from simulator_core.types import DeviceModel
        UP, DOWN = InterfaceState.UP, InterfaceState.DOWN
        first = not self._iface_states
        current: dict[tuple[str, str], tuple] = {}
        for device in sorted(self._topology.devices.values(), key=lambda d: d.id):
            if device.model not in (DeviceModel.SWITCH, DeviceModel.ROUTER):
                continue
            for name, iface in device.interfaces.items():
                key = (device.id, name)
                now = (iface.admin_state, iface.oper_state)
                current[key] = now
                if iface.is_subinterface:
                    continue
                prev = self._iface_states.get(key)
                if prev is None:
                    # New interface (or first computation): previously down,
                    # with the same admin state (no shutdown message).
                    prev = (now[0], DOWN)
                if prev == now:
                    continue
                full = long_name(name)
                (p_admin, p_oper), (n_admin, n_oper) = prev, now
                if p_admin == UP and n_admin == DOWN:
                    self.log_event(device.id, "LINK", 5, "CHANGED",
                                   f"Interface {full}, changed state to administratively down")
                    if p_oper == UP:
                        self.log_event(device.id, "LINEPROTO", 5, "UPDOWN",
                                       f"Line protocol on Interface {full}, changed state to down")
                elif p_oper == DOWN and n_oper == UP:
                    self.log_event(device.id, "LINK", 3, "UPDOWN",
                                   f"Interface {full}, changed state to up")
                    self.log_event(device.id, "LINEPROTO", 5, "UPDOWN",
                                   f"Line protocol on Interface {full}, changed state to up")
                elif p_oper == UP and n_oper == DOWN:
                    self.log_event(device.id, "LINK", 3, "UPDOWN",
                                   f"Interface {full}, changed state to down")
                    self.log_event(device.id, "LINEPROTO", 5, "UPDOWN",
                                   f"Line protocol on Interface {full}, changed state to down")
                elif p_admin == DOWN and n_admin == UP and n_oper == DOWN and not first:
                    self.log_event(device.id, "LINK", 3, "UPDOWN",
                                   f"Interface {full}, changed state to down")
        self._iface_states = current

    # ------------------------------------------------------------------
    # Device accessors
    # ------------------------------------------------------------------

    def get_host(self, device_id: str) -> "Host":
        """Return the Host protocol object for *device_id*."""
        try:
            return self._hosts[device_id]
        except KeyError:
            raise KeyError(f"No host device with id {device_id!r}.")

    def get_switch(self, device_id: str) -> "Switch":
        """Return the Switch protocol object for *device_id*."""
        try:
            return self._switches[device_id]
        except KeyError:
            raise KeyError(f"No switch device with id {device_id!r}.")

    def get_router(self, device_id: str) -> "Router":
        """Return the Router protocol object for *device_id*."""
        try:
            return self._routers[device_id]
        except KeyError:
            raise KeyError(f"No router device with id {device_id!r}.")

    def run_stp(self) -> None:
        """
        Run STP/PVST+ root election and port-role calculation across all
        switches in the topology.

        Call this after the topology is fully connected (all links added)
        or after any change that affects the spanning tree:
         - Bridge priority change
         - Port cost change
         - Link added or removed
         - Interface shut down or brought up
         - VLAN membership change

        The election uses the topology's actual Link objects to discover
        peer switches — no direct cross-object references or hardcoded roots.

        Each STPManager.recalculate() call receives:
         - the topology (for link discovery via topology.neighbours())
         - the full dict of peer STPManagers (for Bridge ID comparison)

        Convergence: iterates until two consecutive snapshots are equal or
        until MAX_ITER (32) iterations, whichever comes first.  32 iterations
        is more than sufficient for realistic educational topologies.
        """
        if not self._switches:
            return
        all_stps = {dev_id: sw.stp for dev_id, sw in self._switches.items()}
        # Elect from scratch: stale root path costs from the previous tree
        # (a removed link, a lowered priority) must not leak into this one.
        for stp in all_stps.values():
            stp.reset_election()
        MAX_ITER = 32
        for _iteration in range(MAX_ITER):
            before = self._stp_snapshot()
            # Sorted iteration order for determinism
            for dev_id in sorted(self._switches):
                self._switches[dev_id].stp.recalculate(self._topology, all_stps)
            after = self._stp_snapshot()
            if after == before:
                break  # stable state reached

    def _stp_snapshot(self) -> dict:
        """Snapshot relevant STP state for convergence detection."""
        snap: dict = {}
        for dev_id, sw in sorted(self._switches.items()):
            snap[dev_id] = {}
            for vlan_id, inst in sw.stp._instances.items():
                ports = {
                    pname: (ps.role, ps.state)
                    for pname, ps in inst.port_states.items()
                }
                snap[dev_id][vlan_id] = (
                    inst.root_bridge_id,
                    inst.root_path_cost,
                    inst.root_port_name,
                    ports,
                )
        return snap

    def _trigger_stp(self) -> None:
        """
        Trigger STP recalculation if the simulation has finished initialising.

        This guard prevents spurious recalculations while _init_devices is
        still building the switch map (before all switches are created).
        """
        if self._stp_initialized:
            self.run_stp()

    # ------------------------------------------------------------------
    # Interface operational state
    # ------------------------------------------------------------------

    def refresh_interface_states(self) -> None:
        """
        Recompute every interface's operational state and rebuild router
        connected routes.

        Call after anything that can change line protocol: ``shutdown`` /
        ``no shutdown``, adding or removing a link, creating or deleting a
        VLAN, or changing a port's VLAN membership.
        """
        self._compute_oper_states()
        self._log_interface_transitions()
        for router in self._routers.values():
            router.update_connected_routes()
        # A port going up or down changes the spanning tree too.
        self._trigger_stp()

    def _compute_oper_states(self) -> None:
        """
        IOS line-protocol rules:

        - administratively down                → down
        - loopback                             → up
        - physical port: up only when cabled, the link is up and the peer
          port is administratively up (an unplugged port is "notconnect")
        - subinterface (``Gi0/0.10``)          → follows its parent port
        - SVI (``Vlan10``) on a switch         → up when at least one up
          physical port carries that VLAN (access member or trunk)
        """
        topo = self._topology
        for device in topo.devices.values():
            for iface in device.interfaces.values():
                if iface.is_svi or iface.is_loopback or iface.is_subinterface:
                    continue
                iface.oper_state = self._physical_oper_state(device.id, iface)
        for device in topo.devices.values():
            for iface in device.interfaces.values():
                if iface.admin_state == InterfaceState.DOWN:
                    if iface.is_svi or iface.is_loopback or iface.is_subinterface:
                        iface.oper_state = InterfaceState.DOWN
                    continue
                if iface.is_loopback:
                    iface.oper_state = InterfaceState.UP
                elif iface.is_subinterface:
                    parent = device.interfaces.get(iface.parent_name)
                    iface.oper_state = (
                        parent.oper_state if parent is not None else InterfaceState.DOWN
                    )
                elif iface.is_svi:
                    iface.oper_state = self._svi_oper_state(device, iface)

    def _physical_oper_state(self, device_id: str, iface) -> InterfaceState:
        if iface.admin_state == InterfaceState.DOWN:
            return InterfaceState.DOWN
        link = self._topology.get_link(device_id, iface.name)
        if link is None or link.admin_state == InterfaceState.DOWN:
            return InterfaceState.DOWN
        peer = self._topology.neighbours(device_id, iface.name)
        if peer is None:
            return InterfaceState.DOWN
        peer_dev = self._topology.devices.get(peer[0])
        peer_iface = peer_dev.interfaces.get(peer[1]) if peer_dev else None
        if peer_iface is None or peer_iface.admin_state == InterfaceState.DOWN:
            return InterfaceState.DOWN
        return InterfaceState.UP

    def _svi_oper_state(self, device, svi) -> InterfaceState:
        from simulator_core.types import DeviceModel
        if device.model != DeviceModel.SWITCH:
            # A router's "interface vlan" has no member ports to track.
            return InterfaceState.UP
        try:
            vlan_id = int(svi.name[4:])
        except ValueError:
            return InterfaceState.DOWN
        for port in device.interfaces.values():
            if port.is_svi or port.is_loopback or port.is_subinterface:
                continue
            if port.oper_state != InterfaceState.UP:
                continue
            if port.switchport_mode == "access" and port.vlan == vlan_id:
                return InterfaceState.UP
            if port.switchport_mode == "trunk" and (
                port.trunk_allowed_vlans is None or vlan_id in port.trunk_allowed_vlans
            ):
                return InterfaceState.UP
        return InterfaceState.DOWN

    def add_link(self, link: "object") -> None:
        """
        Add a link to the working topology and trigger STP recalculation.

        Callers should use this method (rather than topology.add_link directly)
        after Simulation init so that STP converges automatically.
        """
        from simulator_core.topology import Link as _Link
        from simulator_core.exceptions import TopologyError
        assert isinstance(link, _Link)
        for dev_id, iface_name in (link.endpoint_a, link.endpoint_b):
            device = self._topology.devices.get(dev_id)
            if device is None:
                raise TopologyError(f"Device {dev_id!r} is not part of the running lab.")
            iface = device.interfaces.get(iface_name)
            if iface is None or not (iface.is_physical_switchport or device.model.value == "host"):
                raise TopologyError(f"{device.hostname} has no cable port named {iface_name!r}.")
            if self._topology.get_link(dev_id, iface_name) is not None:
                raise TopologyError(f"{device.hostname} {iface_name} is already connected.")
        if link.endpoint_a[0] == link.endpoint_b[0]:
            raise TopologyError("A link cannot connect a device to itself.")
        if any(l.id == link.id for l in self._topology.links):
            raise TopologyError(f"A link with id {link.id!r} already exists.")
        self._topology.add_link(link)
        # Keep it across Wipe (reset restores the snapshot)
        self._topology_snapshot.add_link(copy.deepcopy(link))
        self.refresh_interface_states()   # also re-runs STP

    def remove_link(self, link_id: str) -> None:
        """
        Remove a link from the working topology by ID and trigger STP recalculation.

        Callers should use this method (rather than topology.remove_link directly)
        after Simulation init so that STP converges automatically.
        """
        self._topology.remove_link(link_id)
        self._topology_snapshot.remove_link(link_id)
        self.refresh_interface_states()   # also re-runs STP

    def start_hello_timers(self, start_tick: int = 0) -> None:
        """
        Start (or restart) the periodic BPDU hello chain for all switches.

        Call this after Simulation init (or after reset + init) to begin
        periodic BPDU transmission.  Increments each switch's hello
        generation to invalidate any previously-scheduled chains, then
        schedules the first BPDUHelloEvent at start_tick + hello_time.

        This method is intentionally NOT called automatically from
        _init_devices() to avoid flooding the event queue in unit tests
        that use sim.run() without expecting background BPDU traffic.
        """
        for dev_id in sorted(self._switches):
            # Bump generation to cancel any old chain
            gen = self._hello_generation.get(dev_id, 0) + 1
            self._hello_generation[dev_id] = gen
            self._schedule_next_hello(dev_id, start_tick=start_tick)

    def send_bpdus(self, tick: int = 0) -> None:
        """
        Send BPDUs from all eligible switch ports through the frame pipeline.

        For each switch, for each STP instance (VLAN), for each port that is
        FORWARDING or the root port or a designated port, build a BPDU and
        schedule a FrameTransmit event.  Only ports that are physically
        connected (topology.neighbours returns non-None) and administratively
        UP transmit.

        BPDUs use dst_mac=01:80:c2:00:00:00 (STP multicast) and are carried
        as EthernetFrame.bpdu_payload.  They bypass normal MAC learning and
        STP forwarding checks on receipt.

        Phase 3: calling send_bpdus() does NOT cancel the periodic hello
        chain.  It is a one-shot explicit call used for tests and
        initialisation.  The periodic chain runs independently via
        BPDUHelloEvent.
        """
        import uuid as _uuid
        from simulator_core.frames import EthernetFrame, STP_MULTICAST_MAC
        from simulator_core.stp import BPDU, PortRole
        from simulator_core.addresses import MACAddress
        from simulator_core.types import InterfaceState

        for dev_id in sorted(self._switches):
            sw = self._switches[dev_id]
            device = self._topology.devices.get(dev_id)
            if device is None:
                continue
            for inst in sw.stp.all_instances():
                if inst.bridge_id is None:
                    continue
                for port_name, port_state in inst.port_states.items():
                    # Only send from ports with an eligible role
                    if port_state.role not in (
                        PortRole.DESIGNATED, PortRole.ROOT, PortRole.EDGE
                    ):
                        continue
                    # Phase 6: BPDUFilter suppresses BPDU transmission
                    if port_state.bpdufilter:
                        continue
                    # Must be physically connected
                    peer = self._topology.neighbours(dev_id, port_name)
                    if peer is None:
                        continue
                    # Egress interface must be UP
                    iface = device.interfaces.get(port_name)
                    if iface is None or iface.admin_state == InterfaceState.DOWN:
                        continue
                    # Phase 4: set message_age based on best_bpdu
                    if port_state.best_bpdu is not None:
                        message_age = port_state.best_bpdu.message_age + 1
                    else:
                        message_age = 0  # we are root for this VLAN
                    # Build BPDU
                    bpdu = BPDU(
                        version=2 if sw.stp.mode.value == "rapid-pvst" else 0,
                        root_bridge_id=inst.root_bridge_id,
                        root_path_cost=inst.root_path_cost,
                        bridge_id=inst.bridge_id,
                        port_id=port_state.port_id,
                        message_age=message_age,
                        max_age=inst.timers.max_age,
                        hello_time=inst.timers.hello_time,
                        forward_delay=inst.timers.forward_delay,
                    )
                    # Build EthernetFrame wrapping the BPDU
                    src_mac = iface.mac
                    dst_mac = MACAddress(STP_MULTICAST_MAC)
                    frame = EthernetFrame(
                        src_mac=src_mac,
                        dst_mac=dst_mac,
                        ethertype=EthernetFrame.ETHERTYPE_BPDU,
                        frame_id=str(_uuid.uuid4()),
                        bpdu_payload=bpdu,
                    )
                    # Increment tx counter
                    port_state.bpdu_tx += 1
                    # Schedule FrameTransmit
                    try:
                        self.schedule(FrameTransmit(
                            time=tick,
                            seq=self.next_seq(),
                            device_id=dev_id,
                            interface_name=port_name,
                            frame=frame,
                        ))
                    except Exception:
                        pass  # skip if tick exceeds max_ticks

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _init_devices(self) -> None:
        """Instantiate Host, Switch and Router protocol objects from the topology."""
        # Deferred imports to avoid circular references at module load time.
        from simulator_core.devices.host import Host
        from simulator_core.devices.switch import Switch
        from simulator_core.devices.router import Router
        from simulator_core.types import DeviceModel

        # Guard against _trigger_stp calls while switches are being created.
        self._stp_initialized = False

        # Operational state (line protocol) must be known before routers
        # build their connected routes.  The first transition pass logs the
        # ports that come up as the lab starts.
        self._compute_oper_states()
        self._log_interface_transitions()

        for device in self._topology.devices.values():
            if device.model == DeviceModel.HOST:
                self._hosts[device.id] = Host(device=device, simulation=self)
            elif device.model == DeviceModel.SWITCH:
                self._switches[device.id] = Switch(device=device, simulation=self)
            elif device.model == DeviceModel.ROUTER:
                self._routers[device.id] = Router(device=device, simulation=self)
                # Build initial connected routes from interface IPs
                self._routers[device.id].update_connected_routes()

        # Run initial STP election now that all switches are instantiated
        # and the topology links are known.
        self.run_stp()
        # Allow _trigger_stp to run from this point on.
        self._stp_initialized = True
        # NOTE: Periodic BPDU hello chains and CDP hello chains are NOT started
        # automatically.  Call start_hello_timers() / start_cdp_timers()
        # explicitly after Simulation init to enable periodic transmission.
        # This avoids flooding the event queue during unit tests that use
        # sim.run() without expecting background protocol traffic.

    def _record(self, event: SimulationEvent) -> None:
        """Append the event to the trace, enforcing the trace size cap."""
        if len(self._trace) >= self._max_trace:
            # Append a sentinel at most once per cap crossing.
            if not (self._trace and isinstance(self._trace[-1], TraceLimitReached)):
                sentinel = TraceLimitReached(
                    time=self._clock,
                    seq=self._scheduler.next_seq(),
                    limit=self._max_trace,
                )
                self._trace.append(sentinel)
            return
        self._trace.append(event)

    def _dispatch(self, event: SimulationEvent) -> None:
        """Route a processed event to the correct device handler."""
        if isinstance(event, FrameTransmit):
            self._deliver_frame(event)
        elif isinstance(event, FrameArrival):
            self._handle_frame_arrival(event)
        elif isinstance(event, BPDUHelloEvent):
            self._handle_bpdu_hello(event)
        elif isinstance(event, ForwardDelayEvent):
            self._handle_forward_delay(event)
        elif isinstance(event, CDPHelloEvent):
            self._handle_cdp_hello(event)
        # Other event types (ARP*, ICMP*, MACTable*, drops) are purely
        # observational records — they do not trigger further dispatch.

    def _deliver_frame(self, event: FrameTransmit) -> None:
        """
        Convert a FrameTransmit into a FrameArrival on the peer interface.

        Checks the link state and egress interface state before delivery.
        Schedules a FrameDropped if either is DOWN.
        """
        device_id = event.device_id
        iface_name = event.interface_name
        frame = event.frame

        # --- Check egress interface admin state ---
        device = self._topology.devices.get(device_id)
        if device is None:
            return  # should never happen after validation
        iface = device.interfaces.get(iface_name)
        if iface is None:
            return
        if iface.admin_state == InterfaceState.DOWN:
            self._drop(
                time=event.time + PROPAGATION_DELAY,
                device_id=device_id,
                iface_name=iface_name,
                frame=frame,
                reason=DROP_INTERFACE_ADMIN_DOWN,
            )
            return

        # --- Look up the link ---
        link = self._topology.get_link(device_id, iface_name)
        if link is None or link.admin_state == InterfaceState.DOWN:
            self._drop(
                time=event.time + PROPAGATION_DELAY,
                device_id=device_id,
                iface_name=iface_name,
                frame=frame,
                reason=DROP_LINK_DOWN,
            )
            return

        # --- Find peer ---
        peer = self._topology.neighbours(device_id, iface_name)
        if peer is None:
            # Unconnected interface — drop silently (no peer to receive).
            return

        peer_device_id, peer_iface_name = peer

        # --- Check peer interface admin state ---
        peer_device = self._topology.devices.get(peer_device_id)
        if peer_device is None:
            return
        peer_iface = peer_device.interfaces.get(peer_iface_name)
        if peer_iface is None:
            return
        if peer_iface.admin_state == InterfaceState.DOWN:
            self._drop(
                time=event.time + PROPAGATION_DELAY,
                device_id=peer_device_id,
                iface_name=peer_iface_name,
                frame=frame,
                reason=DROP_INTERFACE_ADMIN_DOWN,
            )
            return

        # --- Schedule FrameArrival ---
        arrive_time = event.time + PROPAGATION_DELAY
        seq = self._scheduler.next_seq()
        arrival = FrameArrival(
            time=arrive_time,
            seq=seq,
            device_id=peer_device_id,
            interface_name=peer_iface_name,
            frame=frame,
        )
        self.schedule(arrival)

        # Update counters.
        if iface is not None:
            iface.tx_frames += 1
        if peer_iface is not None:
            peer_iface.rx_frames += 1

    def _handle_frame_arrival(self, event: FrameArrival) -> None:
        """Route a FrameArrival to the owning device's protocol handler."""
        from simulator_core.types import DeviceModel

        device = self._topology.devices.get(event.device_id)
        if device is None:
            return

        if device.model == DeviceModel.HOST:
            host = self._hosts.get(event.device_id)
            if host is not None:
                host.handle_frame_arrival(event)
        elif device.model == DeviceModel.SWITCH:
            switch = self._switches.get(event.device_id)
            if switch is not None:
                switch.handle_frame_arrival(event)
        elif device.model == DeviceModel.ROUTER:
            router = self._routers.get(event.device_id)
            if router is not None:
                router.handle_frame_arrival(event)

    def _drop(
        self,
        time: int,
        device_id: str,
        iface_name: Optional[str],
        frame: object,  # EthernetFrame
        reason: str,
    ) -> None:
        """Schedule a FrameDropped event and record it immediately."""
        from simulator_core.frames import EthernetFrame

        assert isinstance(frame, EthernetFrame)
        seq = self._scheduler.next_seq()
        drop = FrameDropped(
            time=time,
            seq=seq,
            device_id=device_id,
            interface_name=iface_name,
            frame=frame,
            reason=reason,
        )
        # Record drop events directly rather than scheduling them through the
        # queue — they are consequences of the current event, not future work.
        self._record(drop)

    # ------------------------------------------------------------------
    # BPDU hello timer helpers (Phase 3)
    # ------------------------------------------------------------------

    def _schedule_next_hello(self, device_id: str, start_tick: int,
                             gen: Optional[int] = None) -> None:
        """
        Schedule the next BPDUHelloEvent for a switch.

        ``gen`` must be the generation that owns the current chain.  Callers
        that start a new chain (``start_hello_timers``) pass the generation
        they just wrote; recursive calls from ``_handle_bpdu_hello`` pass the
        generation from the event so the chain never reads a newer generation
        and accidentally creates a duplicate chain.
        """
        sw = self._switches.get(device_id)
        if sw is None:
            return
        # Determine hello_time (in ticks = seconds for this model)
        hello_ticks = 2  # default
        for inst in sw.stp.all_instances():
            hello_ticks = inst.timers.hello_time
            break
        fire_at = start_tick + hello_ticks
        # Stop chain before BPDUs generated here would exceed max_ticks
        if fire_at + PROPAGATION_DELAY > self._max_ticks:
            return
        # Use the caller-supplied generation; fall back to dict only when
        # starting a fresh chain (gen is None means start_hello_timers path
        # where the generation was already written before this call).
        if gen is None:
            gen = self._hello_generation.get(device_id, 0)
        try:
            self.schedule(BPDUHelloEvent(
                time=fire_at,
                seq=self.next_seq(),
                device_id=device_id,
                generation=gen,
            ))
        except Exception:
            pass  # tick exceeds max_ticks — stop the chain silently

    def _handle_bpdu_hello(self, event: BPDUHelloEvent) -> None:
        """
        Handle a BPDUHelloEvent: validate generation, send BPDUs, reschedule.

        If the event's generation is stale (< current generation for this
        switch), it is ignored — the old chain has been superseded by a
        newer one started after a reset or topology change.
        """
        dev_id = event.device_id
        current_gen = self._hello_generation.get(dev_id, 0)
        if event.generation != current_gen:
            # Stale event from an old hello chain — discard it.
            return
        # Send BPDUs for this switch at the current tick.
        self._send_bpdus_for_switch(dev_id, tick=self._clock)
        # Schedule the next hello — pass the validated generation so the
        # chain never accidentally reads a bumped generation and spawns a
        # duplicate chain alongside the existing one.
        self._schedule_next_hello(dev_id, start_tick=self._clock,
                                  gen=event.generation)

    def _send_bpdus_for_switch(self, device_id: str, tick: int) -> None:
        """
        Send BPDUs from one switch at the given tick.

        This is the per-switch variant called by the hello timer.  Identical
        logic to send_bpdus() but scoped to a single switch.  Also performs
        per-port max-age expiry check (Phase 4).
        """
        import uuid as _uuid
        from simulator_core.frames import EthernetFrame, STP_MULTICAST_MAC
        from simulator_core.stp import BPDU, PortRole
        from simulator_core.addresses import MACAddress
        from simulator_core.types import InterfaceState

        sw = self._switches.get(device_id)
        if sw is None:
            return
        device = self._topology.devices.get(device_id)
        if device is None:
            return

        for inst in sw.stp.all_instances():
            if inst.bridge_id is None:
                continue

            # Phase 4: check max-age expiry on all ports before sending
            self._check_max_age_expiry(sw, inst, tick)

            for port_name, port_state in inst.port_states.items():
                if port_state.role not in (
                    PortRole.DESIGNATED, PortRole.ROOT, PortRole.EDGE
                ):
                    continue
                # Phase 6: BPDUFilter suppresses BPDU transmission
                if port_state.bpdufilter:
                    continue
                peer = self._topology.neighbours(device_id, port_name)
                if peer is None:
                    continue
                iface = device.interfaces.get(port_name)
                if iface is None or iface.admin_state == InterfaceState.DOWN:
                    continue

                # Phase 4: set message_age based on best_bpdu
                if port_state.best_bpdu is not None:
                    message_age = port_state.best_bpdu.message_age + 1
                else:
                    message_age = 0  # we are root for this VLAN

                bpdu = BPDU(
                    version=2 if sw.stp.mode.value == "rapid-pvst" else 0,
                    root_bridge_id=inst.root_bridge_id,
                    root_path_cost=inst.root_path_cost,
                    bridge_id=inst.bridge_id,
                    port_id=port_state.port_id,
                    message_age=message_age,
                    max_age=inst.timers.max_age,
                    hello_time=inst.timers.hello_time,
                    forward_delay=inst.timers.forward_delay,
                )
                src_mac = iface.mac
                dst_mac = MACAddress(STP_MULTICAST_MAC)
                frame = EthernetFrame(
                    src_mac=src_mac,
                    dst_mac=dst_mac,
                    ethertype=EthernetFrame.ETHERTYPE_BPDU,
                    frame_id=str(_uuid.uuid4()),
                    bpdu_payload=bpdu,
                )
                port_state.bpdu_tx += 1
                try:
                    self.schedule(FrameTransmit(
                        time=tick,
                        seq=self.next_seq(),
                        device_id=device_id,
                        interface_name=port_name,
                        frame=frame,
                    ))
                except Exception:
                    pass

    def _check_max_age_expiry(self, sw: "Switch", inst: "object", tick: int) -> None:
        """
        Phase 4: expire best_bpdu on ports that have not received a BPDU
        refresh within max_age ticks.  Triggers local recalculation when
        a port's best_bpdu expires.
        """
        from simulator_core.stp import STPInstance, PortState
        assert isinstance(inst, STPInstance)
        max_age_ticks = inst.timers.max_age
        changed = False
        for port_name, ps in inst.port_states.items():
            # Recovery path for ROOT_INCONSISTENT: when best_bpdu is None
            # (cleared by RootGuard on receipt) and the last-seen superior BPDU
            # has aged out, reset the port to DISCARDING so recalculate_from_bpdus
            # can re-assign it as DESIGNATED (the normal role for a root-guarded
            # port when no offending BPDUs are present).
            if ps.state == PortState.ROOT_INCONSISTENT:
                if ps.best_bpdu is None:
                    # best_bpdu was cleared when the guard fired; treat the
                    # absence of a fresh superior BPDU as max-age expiry.
                    if ps.last_bpdu_tick < 0 or (tick - ps.last_bpdu_tick) > max_age_ticks:
                        ps.state = PortState.DISCARDING
                        changed = True
                continue   # skip normal best_bpdu expiry for this port
            if ps.best_bpdu is None:
                continue
            if ps.last_bpdu_tick < 0:
                # Never received a BPDU — do not expire
                continue
            age = tick - ps.last_bpdu_tick
            if age > max_age_ticks:
                # BPDU too old — clear it and trigger recalculation
                ps.best_bpdu = None
                changed = True
        if changed:
            new_learning = sw.stp.recalculate_from_bpdus(inst)
            # Phase 5: schedule ForwardDelayEvents for ports entering LEARNING
            for lport in new_learning:
                self.schedule_forward_delay(
                    device_id=sw.device_id,
                    interface_name=lport,
                    vlan_id=inst.vlan_id,
                    at_tick=self._clock + inst.timers.forward_delay,
                )

    # ------------------------------------------------------------------
    # Forward-delay timer helper (Phase 5)
    # ------------------------------------------------------------------

    def schedule_forward_delay(
        self,
        device_id: str,
        interface_name: str,
        vlan_id: int,
        at_tick: int,
    ) -> None:
        """
        Schedule a ForwardDelayEvent for a port transitioning LEARNING→FORWARDING.

        Called by recalculate_from_bpdus or _recalculate_instance_with_peers
        when a port enters LEARNING state.
        """
        gen = self._hello_generation.get(device_id, 0)
        try:
            self.schedule(ForwardDelayEvent(
                time=at_tick,
                seq=self.next_seq(),
                device_id=device_id,
                interface_name=interface_name,
                vlan_id=vlan_id,
                generation=gen,
            ))
        except Exception:
            pass  # tick exceeds max_ticks

    def _handle_forward_delay(self, event: ForwardDelayEvent) -> None:
        """
        Phase 5: transition port from LEARNING → FORWARDING.

        Only transitions the port if it is still in LEARNING state at fire
        time (a topology change may have already moved it).
        """
        from simulator_core.stp import PortState

        sw = self._switches.get(event.device_id)
        if sw is None:
            return
        inst = sw.stp.get_instance(event.vlan_id)
        if inst is None:
            return
        ps = inst.port_states.get(event.interface_name)
        if ps is None:
            return
        # Only advance if still in LEARNING
        if ps.state == PortState.LEARNING:
            ps.state = PortState.FORWARDING

    # ------------------------------------------------------------------
    # CDP timer helpers
    # ------------------------------------------------------------------

    def start_cdp_timers(self, start_tick: int = 0) -> None:
        """
        Start (or restart) the periodic CDP hello chain for all devices.

        Increments each device's CDP generation to invalidate any previously
        scheduled chains, then schedules the first CDPHelloEvent.

        Called automatically from _init_devices() after STP initialisation.
        """
        all_devices = (
            list(self._switches.keys())
            + list(self._routers.keys())
            + list(self._hosts.keys())
        )
        for dev_id in sorted(all_devices):
            gen = self._cdp_generation.get(dev_id, 0) + 1
            self._cdp_generation[dev_id] = gen
            self._schedule_next_cdp(dev_id, start_tick=start_tick)

    def _schedule_next_cdp(
        self,
        device_id: str,
        start_tick: int,
        gen: Optional[int] = None,
    ) -> None:
        """
        Schedule the next CDPHelloEvent for a device.

        Parameters
        ----------
        device_id:
            The device whose CDP chain is being scheduled.
        start_tick:
            The current logical tick from which the hello interval is added.
        gen:
            The generation that owns the current chain.  If None, reads from
            the dict (used when starting a fresh chain).
        """
        cdp_manager = self._get_cdp_manager(device_id)
        if cdp_manager is None or not cdp_manager.is_enabled:
            return
        hello_ticks = cdp_manager.hello_interval
        fire_at = start_tick + hello_ticks
        # Stop chain if it would exceed max_ticks
        if fire_at + PROPAGATION_DELAY > self._max_ticks:
            return
        if gen is None:
            gen = self._cdp_generation.get(device_id, 0)
        try:
            self.schedule(CDPHelloEvent(
                time=fire_at,
                seq=self.next_seq(),
                device_id=device_id,
                generation=gen,
            ))
        except Exception:
            pass  # tick exceeds max_ticks — stop the chain silently

    def _handle_cdp_hello(self, event: CDPHelloEvent) -> None:
        """
        Handle a CDPHelloEvent: validate generation, send CDP frames, reschedule.

        If the event's generation is stale (< current generation for this
        device), it is ignored — the old chain has been superseded by a newer
        one started after a reset or topology change.
        """
        dev_id = event.device_id
        current_gen = self._cdp_generation.get(dev_id, 0)
        if event.generation != current_gen:
            # Stale event from an old CDP chain — discard it.
            return
        self._send_cdp_for_device(dev_id, tick=self._clock)
        self._check_cdp_expiry(dev_id, tick=self._clock)
        # Reschedule — pass the validated generation so the chain never
        # accidentally reads a bumped generation and spawns a duplicate chain.
        self._schedule_next_cdp(dev_id, start_tick=self._clock, gen=event.generation)

    def _send_cdp_for_device(self, device_id: str, tick: int) -> None:
        """
        Send CDP frames from one device at the given tick.

        Iterates UP physical interfaces that have a connected link, builds a
        CDPEntry, wraps it in an EthernetFrame, and schedules a FrameTransmit.
        SVIs and loopbacks are skipped.
        """
        import uuid as _uuid
        from simulator_core.frames import EthernetFrame, CDP_MULTICAST_MAC, ETHERTYPE_CDP
        from simulator_core.cdp import CDPEntry
        from simulator_core.addresses import MACAddress
        from simulator_core.types import DeviceModel, InterfaceState

        cdp_manager = self._get_cdp_manager(device_id)
        if cdp_manager is None or not cdp_manager.is_enabled:
            return

        device = self._topology.devices.get(device_id)
        if device is None:
            return

        # Collect all configured IP addresses on this device
        ip_addresses: list[str] = []
        for iface in device.interfaces.values():
            if iface.ip_config is not None:
                ip_addresses.append(str(iface.ip_config.address))

        # Determine capabilities and platform from device model
        if device.model == DeviceModel.SWITCH:
            capabilities = "Switch"
            platform = "Cisco Catalyst 2960"
        elif device.model == DeviceModel.ROUTER:
            capabilities = "Router"
            platform = "Cisco ISR 2911"
        else:
            capabilities = "Host"
            platform = "Generic Host"

        for iface_name, iface in device.interfaces.items():
            # Skip logical interfaces
            if iface.is_svi or iface.is_loopback:
                continue
            # Skip admin-down interfaces
            if iface.admin_state == InterfaceState.DOWN:
                continue
            # Skip unconnected interfaces
            peer = self._topology.neighbours(device_id, iface_name)
            if peer is None:
                continue

            entry = CDPEntry(
                device_id=cdp_manager.hostname,
                local_interface=iface_name,
                holdtime=cdp_manager.holdtime,
                capabilities=capabilities,
                platform=platform,
                software_version="NetLab Academy Simulator 1.0",
                ip_addresses=tuple(ip_addresses),
                native_vlan=getattr(iface, "trunk_native_vlan", 1) or 1,
                duplex="full",
                vtp_domain="",
                advertisement_version=2,
            )

            src_mac = iface.mac
            dst_mac = MACAddress(CDP_MULTICAST_MAC)
            frame = EthernetFrame(
                src_mac=src_mac,
                dst_mac=dst_mac,
                ethertype=ETHERTYPE_CDP,
                frame_id=str(_uuid.uuid4()),
                cdp_payload=entry,
            )
            try:
                self.schedule(FrameTransmit(
                    time=tick,
                    seq=self.next_seq(),
                    device_id=device_id,
                    interface_name=iface_name,
                    frame=frame,
                ))
            except Exception:
                pass  # tick exceeds max_ticks

    def _check_cdp_expiry(self, device_id: str, tick: int) -> None:
        """Expire stale CDP neighbor entries on all devices."""
        for mgr_dict in [self._switches, self._routers, self._hosts]:
            for dev in mgr_dict.values():
                if hasattr(dev, "cdp_manager"):
                    dev.cdp_manager.expire_neighbors(tick)

    def _get_cdp_manager(self, device_id: str):
        """Return the CDPManager for any device type, or None."""
        sw = self._switches.get(device_id)
        if sw is not None:
            return getattr(sw, "cdp_manager", None)
        rtr = self._routers.get(device_id)
        if rtr is not None:
            return getattr(rtr, "cdp_manager", None)
        host = self._hosts.get(device_id)
        if host is not None:
            return getattr(host, "cdp_manager", None)
        return None
